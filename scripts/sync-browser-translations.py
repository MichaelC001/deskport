#!/usr/bin/env python3
"""Generate browser resources from the pinned core's explicit Web context."""
import argparse
import importlib.util
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('deskport_ui_catalog', ROOT/'shared/deskport-core/i18n/catalog.py')
core = importlib.util.module_from_spec(spec)
spec.loader.exec_module(core)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
rows = {key: row for key, row in core.records().items() if 'Browser' in row.get('_web', [])}
languages = [{key: language[key] for key in ('code', 'name', 'direction')} for language in core.languages()]
strings = {}
fallbacks = {}
for language in languages:
    code = language['code']
    strings[code] = {}
    fallbacks[code] = []
    for source, row in rows.items():
        text = row.get('_webTranslations', {}).get('Browser', {}).get(code, row.get(code))
        if not text:
            text = source
            fallbacks[code].append(source)
        if sorted(core.placeholders(source)) != sorted(core.placeholders(text)):
            raise SystemExit(f'Browser placeholder mismatch: {code}: {source}')
        strings[code][source] = text
payload = {'context': 'Browser', 'languages': languages, 'strings': strings, 'fallbacks': fallbacks}
expected = '// Generated by scripts/sync-browser-translations.py from pinned deskport-core.\n// SPDX-License-Identifier: GPL-3.0-or-later\nwindow.DeskPortUIResources = '+json.dumps(payload, ensure_ascii=False, separators=(',', ':'))+';\n'
path = ROOT/'app/browser/i18n-data.js'
if args.check:
    if not path.exists() or path.read_text() != expected:
        raise SystemExit('Regenerate Web resources with scripts/sync-browser-translations.py')
else:
    path.write_text(expected)
print(f'PASS: {len(rows)} Web originals × {len(languages)} locales generated from core (explicit English fallback)')
